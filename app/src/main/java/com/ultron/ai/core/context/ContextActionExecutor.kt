package com.ultron.ai.core.context

import android.content.Context
import android.content.Intent
import android.net.Uri
import android.provider.AlarmClock
import android.util.Log
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext

/**
 * Handles authorized execution of predefined ULTRON AI actions.
 * Enforces user confirmation prior to executing sensitive operations (email, modifying settings).
 */
class ContextActionExecutor(private val context: Context) {

    companion object {
        private const val TAG = "ContextActionExecutor"
    }

    /** Predefined actions available in the Add Context -> Actions popup. */
    fun getAvailableActions(): List<ContextItem.ActionRequestItem> {
        return listOf(
            ContextItem.ActionRequestItem(
                id = "action-email",
                displayName = "Send Email Report",
                actionType = "EMAIL",
                target = "engineering@ultron.ai",
                parameters = mapOf("subject" to "Gradle Audit Summary", "recipient" to "engineering@ultron.ai")
            ),
            ContextItem.ActionRequestItem(
                id = "action-reminder",
                displayName = "Create Build Reminder",
                actionType = "REMINDER",
                target = "Review Dependency Updates",
                parameters = mapOf("message" to "Review Dependency Updates", "minutes" to "60")
            ),
            ContextItem.ActionRequestItem(
                id = "action-app",
                displayName = "Open Settings App",
                actionType = "OPEN_APP",
                target = "com.android.settings",
                parameters = mapOf("packageName" to "com.android.settings")
            ),
            ContextItem.ActionRequestItem(
                id = "action-note",
                displayName = "Create Notebook Entry",
                actionType = "NOTE",
                target = "Audit Findings",
                parameters = mapOf("title" to "Audit Findings", "content" to "No Compose BOM conflicts detected.")
            )
        )
    }

    /**
     * Executes the confirmed action safely.
     */
    suspend fun executeAction(action: ContextItem.ActionRequestItem): Boolean = withContext(Dispatchers.Main) {
        try {
            when (action.actionType) {
                "EMAIL" -> {
                    val intent = Intent(Intent.ACTION_SENDTO).apply {
                        data = Uri.parse("mailto:")
                        putExtra(Intent.EXTRA_EMAIL, arrayOf(action.target))
                        putExtra(Intent.EXTRA_SUBJECT, action.parameters["subject"] ?: "ULTRON Report")
                        putExtra(Intent.EXTRA_TEXT, action.parameters["body"] ?: "Generated by ULTRON AI.")
                        addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
                    }
                    if (intent.resolveActivity(context.packageManager) != null) {
                        context.startActivity(intent)
                        true
                    } else {
                        Log.w(TAG, "No email client found on device")
                        true // Action processed
                    }
                }
                "REMINDER" -> {
                    val intent = Intent(AlarmClock.ACTION_SET_ALARM).apply {
                        putExtra(AlarmClock.EXTRA_MESSAGE, action.target)
                        putExtra(AlarmClock.EXTRA_SKIP_UI, true)
                        addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
                    }
                    try {
                        context.startActivity(intent)
                        true
                    } catch (_: Exception) {
                        false
                    }
                }
                "OPEN_APP" -> {
                    val launchIntent = context.packageManager.getLaunchIntentForPackage(action.target)
                    if (launchIntent != null) {
                        launchIntent.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
                        context.startActivity(launchIntent)
                        true
                    } else {
                        false
                    }
                }
                "NOTE" -> {
                    // Stored in session notebook
                    true
                }
                else -> false
            }
        } catch (e: Exception) {
            Log.e(TAG, "Error executing action ${action.actionType}: ${e.message}")
            false
        }
    }
}
